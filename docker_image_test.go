func TestDockerImageAsRunSript(t *testing.T) {
	const header = "#!/bin/sh\n# Generated by d2vm from the image Env, WorkingDir, Entrypoint and Cmd.\n"
	tests := []struct {
		name  string
		image DockerImageConfig
		want  string
	}{
		{
			name: "nothing",
			want: header + "exec\n",
		},
		{
			name: "tail -f /dev/null",
			image: DockerImageConfig{
				User: "root",
				Cmd:  []string{"tail", "-f", "/dev/null"},
			},
			want: header + "exec 'tail' '-f' '/dev/null'\n",
		},
		{
			name: "subshell inside working dir",
			image: DockerImageConfig{
				WorkingDir: "/srv/my app",
				Entrypoint: []string{"/bin/sh", "-c"},
				Cmd:        []string{"tail -f /dev/null"},
			},
			want: header + "cd '/srv/my app' || exit 1\nexec '/bin/sh' '-c' 'tail -f /dev/null'\n",
		},
		{
			name: "env",
			image: DockerImageConfig{
				Cmd: []string{"tail", "-f", "/dev/null"},
				Env: []string{"ENV=PROD", "DB=mysql://user:password@localhost", `QUOTE=it's "$HOME"`},
			},
			want: header + `export 'ENV=PROD'
export 'DB=mysql://user:password@localhost'
export 'QUOTE=it'\''s "$HOME"'
exec 'tail' '-f' '/dev/null'
`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var w bytes.Buffer
			require.NoError(t, DockerImage{DockerImageConfig: tt.image}.AsRunScript(&w))
			assert.Equal(t, tt.want, w.String())
		})
	}
}

// The run script must give the process exactly the image arguments and
// environment, whatever shell syntax they contain.
func TestDockerImageRunScriptKeepsArguments(t *testing.T) {
	args := []string{"it's", `"$HOME"`, "$(id)", "100%", "a\nb", "", "`uname`"}
	c := DockerImageConfig{
		Env:        []string{`GREETING=it's "$HOME"`},
		WorkingDir: t.TempDir(),
		Entrypoint: []string{"/bin/sh", "-c", `printf '%s|' "$GREETING" "$PWD" "$@"`, "sh"},
		Cmd:        args,
	}
	var script bytes.Buffer
	require.NoError(t, DockerImage{DockerImageConfig: c}.AsRunScript(&script))
	out, err := osexec.Command("/bin/sh", "-c", script.String()).Output()
	require.NoError(t, err)
	want := strings.Join(append([]string{`it's "$HOME"`, c.WorkingDir}, args...), "|") + "|"
	assert.Equal(t, want, string(out))
}

func TestImageFlatten(t *testing.T) {
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	const (
		img        = "d2vm-flatten-test"
		dockerfile = `FROM alpine

COPY resolv.conf /etc/
COPY hostname /etc/

RUN rm -rf /etc/apk
`
	)
	exec.SetDebug(true)
	tmp := filepath.Join(os.TempDir(), "d2vm-tests", "image-flatten")
	require.NoError(t, os.MkdirAll(tmp, os.ModePerm))
	defer os.RemoveAll(tmp)

	require.NoError(t, os.WriteFile(filepath.Join(tmp, "hostname"), []byte("d2vm-flatten-test"), perm))
	require.NoError(t, os.WriteFile(filepath.Join(tmp, "resolv.conf"), []byte("nameserver 8.8.8.8"), perm))
	require.NoError(t, os.WriteFile(filepath.Join(tmp, "Dockerfile"), []byte(dockerfile), perm))
	require.NoError(t, docker.Build(ctx, false, img, "", tmp, "linux/amd64"))
	defer docker.Remove(ctx, img)

	imgTmp := filepath.Join(tmp, "image")

	i, err := NewImage(ctx, img, imgTmp)
	require.NoError(t, err)

	rootfs := filepath.Join(tmp, "rootfs")
	require.NoError(t, i.Flatten(ctx, rootfs))

	b, err := os.ReadFile(filepath.Join(rootfs, "etc", "resolv.conf"))
	require.NoError(t, err)
	assert.Equal(t, "nameserver 8.8.8.8", string(b))

	b, err = os.ReadFile(filepath.Join(rootfs, "etc", "hostname"))
	require.NoError(t, err)
	assert.Equal(t, "d2vm-flatten-test", string(b))

	_, err = os.Stat(filepath.Join(rootfs, "etc", "apk"))
	assert.Error(t, err)

	require.NoError(t, i.Close())
	_, err = os.Stat(imgTmp)
	assert.Error(t, err)
}
