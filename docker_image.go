const (
	entrypointName   = "oci2vm-entrypoint"
	entrypointScript = "/usr/local/bin/" + entrypointName

	// The script does not switch user: the service manager runs it as the image
	// user, which also works for numeric uid:gid values.
	dockerImageRun = `#!/bin/sh
# Generated by oci2vm from the image Env, WorkingDir, Entrypoint and Cmd.
{{- range .DockerImageConfig.Env }}
export {{ quote . }}
{{- end }}
{{- with .DockerImageConfig.WorkingDir }}
cd {{ quote . }} || exit 1
{{- end }}
exec{{ range .DockerImageConfig.Entrypoint }} {{ quote . }}{{ end }}{{ range .DockerImageConfig.Cmd }} {{ quote . }}{{ end }}
`

	entrypointSystemdUnit = `[Unit]
Description=Image entrypoint (generated by oci2vm)
Wants=network-online.target
After=network-online.target

[Service]
ExecStart={{ .Script }}
User={{ .User }}
{{- with .Group }}
Group={{ . }}
{{- end }}
Restart=on-failure

[Install]
WantedBy=multi-user.target
`

	entrypointOpenRCService = `#!/sbin/openrc-run
description="Image entrypoint (generated by oci2vm)"
command={{ quote .Script }}
command_user={{ quote .UserGroup }}
supervisor="supervise-daemon"
output_log="/var/log/{{ .Name }}.log"
error_log="/var/log/{{ .Name }}.log"

depend() {
	need net
}

start_pre() {
	# supervise-daemon opens the log as command_user, who cannot create it in /var/log
	checkpath --file --owner "$command_user" --mode 0640 "$output_log"
}
`
)

var (
	tplShellFuncs = template.FuncMap{"quote": shellQuote}

	dockerImageRunTemplate          = template.Must(template.New("docker-run.sh").Funcs(tplShellFuncs).Parse(dockerImageRun))
	entrypointSystemdUnitTemplate   = template.Must(template.New(entrypointName + ".service").Parse(entrypointSystemdUnit))
	entrypointOpenRCServiceTemplate = template.Must(template.New(entrypointName).Funcs(tplShellFuncs).Parse(entrypointOpenRCService))

	_ = cmd.NewCmdFlatten
)

// shellQuote quotes s for POSIX sh: everything inside single quotes is
// literal, and an embedded single quote ends the quoted string, is written
// escaped, then the quoting starts again.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

type DockerImage struct {
	DockerImageConfig `json:"Config"`
	Architecture      string `json:"Architecture"`
	Os                string `json:"Os"`
	Size              int    `json:"Size"`
}

type DockerImageConfig struct {
	Image      string   `json:"Image"`
	Hostname   string   `json:"Hostname"`
	Domainname string   `json:"Domainname"`
	User       string   `json:"User"`
	Env        []string `json:"Env"`
	Cmd        []string `json:"Cmd"`
	WorkingDir string   `json:"WorkingDir"`
	Entrypoint []string `json:"Entrypoint"`
}

func (i DockerImage) AsRunScript(w io.Writer) error {
	return dockerImageRunTemplate.Execute(w, i)
}

// entrypointService is the service running the entrypoint script as the image
// user, rendered as a systemd unit or an OpenRC service.
type entrypointService struct {
	Name   string
	Script string
	User   string
	Group  string
}

func newEntrypointService(imageUser string) entrypointService {
	user, group, _ := strings.Cut(imageUser, ":")
	return entrypointService{Name: entrypointName, Script: entrypointScript, User: cmp.Or(user, "root"), Group: group}
}

// UserGroup returns the user[:group] form expected by OpenRC command_user.
func (s entrypointService) UserGroup() string {
	if s.Group == "" {
		return s.User
	}
	return s.User + ":" + s.Group
}

// FetchDockerImageConfig returns the runtime configuration recorded in the
// image: entrypoint, command, environment, working directory and user.
func FetchDockerImageConfig(ctx context.Context, img string) (DockerImageConfig, error) {
	o, _, err := docker.CmdOut(ctx, "image", "inspect", "--format", "{{json .Config}}", img)
	if err != nil {
		return DockerImageConfig{}, err
	}
	var c DockerImageConfig
	if err := json.Unmarshal([]byte(o), &c); err != nil {
		return DockerImageConfig{}, fmt.Errorf("failed to parse %s image config: %w", img, err)
	}
	return c, nil
}

func NewImage(ctx context.Context, tag string, imageTmpPath string) (*image, error) {
	if err := os.MkdirAll(imageTmpPath, os.ModePerm); err != nil {
		return nil, err
	}
	// save the image to a tar file to avoid loading it in memory
	tar := filepath.Join(imageTmpPath, "img.layers.tar")
	if err := docker.ImageSave(ctx, tag, tar); err != nil {
		return nil, err
	}
	img, err := crane.Load(tar)
	if err != nil {
		return nil, err
	}
	i := &image{
		img: img,
		dir: imageTmpPath,
	}
	return i, nil
}

type image struct {
	tag      string
	img      v1.Image
	dir      string
	Config   string   `json:"Config"`
	RepoTags []string `json:"RepoTags"`
	Layers   []string `json:"Layers"`
}

func (i image) Flatten(ctx context.Context, out string) error {
	if err := os.MkdirAll(out, os.ModePerm); err != nil {
		return err
	}
	tar := filepath.Join(i.dir, "img.tar")
	f, err := os.Create(tar)
	if err != nil {
		return err
	}
	defer f.Close()
	if _, err := io.Copy(f, mutate.Extract(i.img)); err != nil {
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := exec.Run(ctx, "tar", "xvf", tar, "-C", out); err != nil {
		return err
	}
	return nil
}

func (i image) Close() error {
	return os.RemoveAll(i.dir)
}
